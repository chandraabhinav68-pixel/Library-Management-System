package com.bookhaven.config;

import com.bookhaven.exception.DataAccessException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/** Owns JDBC connection creation and creates the local database on first launch. */
public final class Database {
    private static final String URL = System.getProperty("bookhaven.db.url",
            "jdbc:h2:file:./data/bookhaven-library;DB_CLOSE_ON_EXIT=FALSE;DATABASE_TO_UPPER=FALSE");

    private Database() { }

    public static Connection connect() throws SQLException { return DriverManager.getConnection(URL, "sa", ""); }

    public static void initialize() {
        try {
            Files.createDirectories(Path.of("data"));
            try (Connection connection = connect(); Statement statement = connection.createStatement()) {
                statement.execute("CREATE TABLE IF NOT EXISTS books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(180) NOT NULL, author VARCHAR(140) NOT NULL, isbn VARCHAR(32) NOT NULL UNIQUE, category VARCHAR(80) NOT NULL, total_copies INT NOT NULL CHECK (total_copies > 0))");
                statement.execute("CREATE TABLE IF NOT EXISTS members (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE, phone VARCHAR(40) NOT NULL, joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
                statement.execute("CREATE TABLE IF NOT EXISTS loans (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id BIGINT NOT NULL REFERENCES books(id), member_id BIGINT NOT NULL REFERENCES members(id), borrowed_on DATE NOT NULL, due_on DATE NOT NULL, returned_on DATE)");
                statement.execute("CREATE INDEX IF NOT EXISTS idx_loans_active ON loans(book_id, returned_on)");
                statement.execute("MERGE INTO books (title,author,isbn,category,total_copies) KEY(isbn) VALUES ('The Midnight Library','Matt Haig','9780525559474','Fiction',4),('Atomic Habits','James Clear','9780735211292','Personal Growth',3),('The Hobbit','J. R. R. Tolkien','9780007525492','Fantasy',2),('Educated','Tara Westover','9780399590504','Memoir',2),('Project Hail Mary','Andy Weir','9780593135204','Science Fiction',3)");
                statement.execute("MERGE INTO members (name,email,phone) KEY(email) VALUES ('Asha Rao','asha@example.com','9876543210'),('Arjun Mehta','arjun@example.com','9876543211')");
                resetIdentity(connection,"books");
                resetIdentity(connection,"members");
                resetIdentity(connection,"loans");
            }
        } catch (Exception exception) {
            throw new DataAccessException("Could not initialize the library database", exception);
        }
    }

    private static void resetIdentity(Connection connection,String table) throws SQLException {
        long nextId;
        try(Statement statement=connection.createStatement();var result=statement.executeQuery("SELECT COALESCE(MAX(id),0)+1 FROM "+table)){
            result.next();nextId=result.getLong(1);
        }
        try(Statement statement=connection.createStatement()){
            statement.execute("ALTER TABLE "+table+" ALTER COLUMN id RESTART WITH "+nextId);
        }
    }
}
