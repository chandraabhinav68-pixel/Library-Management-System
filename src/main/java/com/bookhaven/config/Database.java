package com.bookhaven.config;

import com.bookhaven.exception.DataAccessException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/** Owns JDBC connection creation and creates the local database on first launch. */
public final class Database {
    private static final String URL = System.getProperty("bookhaven.db.url",
            System.getenv().getOrDefault("BOOKHAVEN_DB_URL",
                    "jdbc:h2:file:./data/bookhaven-library;DB_CLOSE_ON_EXIT=FALSE;DATABASE_TO_UPPER=FALSE"));
    private static final String USER = System.getProperty("bookhaven.db.user",
            System.getenv().getOrDefault("BOOKHAVEN_DB_USER", "sa"));
    private static final String PASSWORD = System.getProperty("bookhaven.db.password",
            System.getenv().getOrDefault("BOOKHAVEN_DB_PASSWORD", ""));

    private Database() { }

    public static Connection connect() throws SQLException { return DriverManager.getConnection(URL, USER, PASSWORD); }

    public static void initialize() {
        try {
            Files.createDirectories(Path.of("data"));
            try (Connection connection = connect(); Statement statement = connection.createStatement()) {
                statement.execute("CREATE TABLE IF NOT EXISTS books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(180) NOT NULL, author VARCHAR(140) NOT NULL, isbn VARCHAR(32) NOT NULL UNIQUE, category VARCHAR(80) NOT NULL, total_copies INT NOT NULL CHECK (total_copies > 0))");
                statement.execute("CREATE TABLE IF NOT EXISTS members (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE, phone VARCHAR(40) NOT NULL, joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
                statement.execute("CREATE TABLE IF NOT EXISTS loans (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id BIGINT NOT NULL REFERENCES books(id), member_id BIGINT NOT NULL REFERENCES members(id), borrowed_on DATE NOT NULL, due_on DATE NOT NULL, returned_on DATE)");
                statement.execute("CREATE INDEX IF NOT EXISTS idx_loans_active ON loans(book_id, returned_on)");
                seedBooks(connection);
                seedMembers(connection);
            }
        } catch (Exception exception) {
            throw new DataAccessException("Could not initialize the library database", exception);
        }
    }

    private static void seedBooks(Connection connection) throws SQLException {
        String[][] books = {
                {"The Midnight Library", "Matt Haig", "9780525559474", "Fiction", "4"},
                {"Atomic Habits", "James Clear", "9780735211292", "Personal Growth", "3"},
                {"The Hobbit", "J. R. R. Tolkien", "9780007525492", "Fantasy", "2"},
                {"Educated", "Tara Westover", "9780399590504", "Memoir", "2"},
                {"Project Hail Mary", "Andy Weir", "9780593135204", "Science Fiction", "3"}
        };
        for (String[] book : books) {
            if (exists(connection, "SELECT 1 FROM books WHERE isbn=?", book[2])) continue;
            try (PreparedStatement insert = connection.prepareStatement(
                    "INSERT INTO books(title,author,isbn,category,total_copies) VALUES(?,?,?,?,?)")) {
                insert.setString(1, book[0]); insert.setString(2, book[1]); insert.setString(3, book[2]);
                insert.setString(4, book[3]); insert.setInt(5, Integer.parseInt(book[4])); insert.executeUpdate();
            }
        }
    }

    private static void seedMembers(Connection connection) throws SQLException {
        String[][] members = {{"Asha Rao", "asha@example.com", "9876543210"},
                {"Arjun Mehta", "arjun@example.com", "9876543211"}};
        for (String[] member : members) {
            if (exists(connection, "SELECT 1 FROM members WHERE email=?", member[1])) continue;
            try (PreparedStatement insert = connection.prepareStatement(
                    "INSERT INTO members(name,email,phone) VALUES(?,?,?)")) {
                insert.setString(1, member[0]); insert.setString(2, member[1]); insert.setString(3, member[2]);
                insert.executeUpdate();
            }
        }
    }

    private static boolean exists(Connection connection, String sql, String value) throws SQLException {
        try (PreparedStatement query = connection.prepareStatement(sql)) {
            query.setString(1, value);
            try (ResultSet rows = query.executeQuery()) { return rows.next(); }
        }
    }
}
